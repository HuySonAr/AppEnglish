import { DataSource } from 'typeorm';
import {
  PracticePromptEntity,
  PracticePromptVersionEntity,
  SwTestEntity,
  SwTestVersionEntity,
  ContentEventEntity,
  ProcessedMessageEntity,
  AdminNoticeEntity,
  AdminNoticeReadEntity,
  ExamTypeEntity,
  LessonEntity,
  LessonVersionEntity,
  ListeningExerciseEntity,
  ListeningExerciseVersionEntity,
  ListeningTimingJobEntity,
  ListeningTopicEntity,
  ListeningTestEntity,
  MediaAssetEntity,
  MockTestEntity,
  MockTestVersionEntity,
  PlacementVersionEntity,
  UnitEntity,
  UnitReviewVersionEntity,
} from './content.entities.js';

export function createContentDataSource() {
  return new DataSource({
    type: 'postgres',
    host: process.env.POSTGRES_HOST || 'localhost',
    port: Number(process.env.POSTGRES_PORT || 5432),
    username: process.env.POSTGRES_USER || 'postgres',
    password: process.env.POSTGRES_PASSWORD,
    database: process.env.CONTENT_DATABASE_NAME || 'app_content',
    entities: [
      UnitEntity,
      UnitReviewVersionEntity,
      LessonEntity,
      LessonVersionEntity,
      MediaAssetEntity,
      PlacementVersionEntity,
      MockTestEntity,
      MockTestVersionEntity,
      ExamTypeEntity,
      ListeningTopicEntity,
      ListeningTestEntity,
      ListeningExerciseEntity,
      ListeningExerciseVersionEntity,
      ListeningTimingJobEntity,
      AdminNoticeEntity,
      AdminNoticeReadEntity,
      ContentEventEntity,
      ProcessedMessageEntity,
      PracticePromptEntity,
      PracticePromptVersionEntity,
      SwTestEntity,
      SwTestVersionEntity,
    ],
    migrations: ['src/database/migrations/*.js'],
  });
}
